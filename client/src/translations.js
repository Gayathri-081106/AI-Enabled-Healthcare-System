const LanguageContext = createContext({
  language: 'English',
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
  languages: SUPPORTED_LANGUAGES
});

export function LanguageProvider({ children, currentUser }) {
  // Initialize from user preference, localStorage, or English
  const [language, setLanguageState] = useState(() => {
    if (currentUser?.id) {
      const userSaved = localStorage.getItem(`user_${currentUser.id}_lang`);
      if (userSaved && TRANSLATIONS[userSaved]) return userSaved;
    }
    const globalSaved = localStorage.getItem('mediconnect_language');
    if (globalSaved && TRANSLATIONS[globalSaved]) return globalSaved;
    if (currentUser?.language && TRANSLATIONS[currentUser.language]) return currentUser.language;
    return 'English';
  });

  // Sync when currentUser changes
  useEffect(() => {
    if (currentUser?.id) {
      const userSaved = localStorage.getItem(`user_${currentUser.id}_lang`);
      if (userSaved && TRANSLATIONS[userSaved]) {
        setLanguageState(userSaved);
      } else if (currentUser.language && TRANSLATIONS[currentUser.language]) {
        setLanguageState(currentUser.language);
        localStorage.setItem(`user_${currentUser.id}_lang`, currentUser.language);
        localStorage.setItem('mediconnect_language', currentUser.language);
      }
    }
  }, [currentUser?.id, currentUser?.language]);

  const setLanguage = (newLang) => {
    if (!TRANSLATIONS[newLang]) return;
    setLanguageState(newLang);
    localStorage.setItem('mediconnect_language', newLang);
    const token = localStorage.getItem('token');
    const userStr = localStorage.getItem('user');
    let u = currentUser;
    if (!u && userStr) {
      try { u = JSON.parse(userStr); } catch (e) {}
    }
    if (u?.id) {
      localStorage.setItem(`user_${u.id}_lang`, newLang);
    }
    if (token) {
      fetch('http://localhost:5000/api/auth/language', {
        method: 'PUT',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${token}`
        },
        body: JSON.stringify({ language: newLang })
      }).catch(() => {});
    }
  };

  const t = (key, fallback) => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS.English;
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    if (TRANSLATIONS.English && TRANSLATIONS.English[key] !== undefined) {
      return TRANSLATIONS.English[key];
    }
    return fallback !== undefined ? fallback : key;
  };

  return React.createElement(
    LanguageContext.Provider,
    { value: { language, setLanguage, t, languages: SUPPORTED_LANGUAGES } },
    children
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

export function LanguageSelector({ className = '', style = {}, compact = false }) {
  const { language, setLanguage, languages, t } = useLanguage();

  return React.createElement(
    'div',
    {
      className: `language-selector-wrapper ${className}`,
      style: {
        display: 'inline-flex',
        alignItems: 'center',
        ...style
      },
      title: t ? t('select_language', 'Language') : 'Language'
    },
    React.createElement(
      'div',
      {
        className: 'language-selector-pill',
        style: {
          display: 'inline-flex',
          alignItems: 'center',
          gap: 6,
          background: 'var(--bg-subtle, #f1f5f9)',
          border: '1px solid var(--border-color, #e2e8f0)',
          borderRadius: 20,
          padding: compact ? '2px 8px' : '4px 10px',
          boxShadow: '0 1px 2px rgba(0,0,0,0.05)'
        }
      },
      React.createElement('span', { style: { fontSize: '0.95rem' }, role: 'img', 'aria-label': 'Language' }, '🌐'),
      React.createElement(
        'select',
        {
          value: language,
          onChange: (e) => setLanguage(e.target.value),
          'aria-label': 'Select Language',
          style: {
            background: 'transparent',
            border: 'none',
            outline: 'none',
            fontSize: '0.84rem',
            fontWeight: 600,
            color: 'var(--text-main, #0f172a)',
            cursor: 'pointer',
            paddingRight: 2
          }
        },
        languages.map((l) =>
          React.createElement(
            'option',
            { key: l.code, value: l.code, style: { color: '#0f172a', background: '#ffffff' } },
            `${l.nativeName} (${l.name})`
          )
        )
      )
    )
  );
}


